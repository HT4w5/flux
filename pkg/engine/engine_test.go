// readYAMLChains reads a YAML file into []ChainConfig.
// Each top-level item must have the shape of ChainConfig.
func readYAMLChains(t *testing.T, path string) []ChainConfig {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read file %s: %v", path, err)
	}
	var chains []ChainConfig
	if err := yaml.Unmarshal(data, &chains); err != nil {
		t.Fatalf("unmarshal %s: %v", path, err)
	}
	return chains
}

// renameMainTo picks the chain with name=from and renames it to "main".
// Other chains are returned unchanged.  This lets YAML files declare their
// entrypoint chain with a human-readable name.
func renameMainTo(chains []ChainConfig, from string) []ChainConfig {
	out := make([]ChainConfig, len(chains))
	copy(out, chains)
	for i := range out {
		if out[i].Name == from {
			out[i].Name = "main"
			return out
		}
	}
	return out
}

