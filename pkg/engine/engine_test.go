func TestBanAndLogStatements(t *testing.T) {
	jail := newStubJail()
	fsi := newStubFileSizeIndex(map[string]int64{})
	addr1 := netip.MustParseAddr("10.0.0.1")

	chains := readYAMLChains(t, "testdata/ban_log.yaml")

	t.Run("BAN duration 30m", func(t *testing.T) {
		jail.bans = jail.bans[:0]
		// channel is now engine-owned
		re := New(
			WithJail(jail),
			WithFileSizeIndex(fsi),
			WithCache(cache.NewCCacheCache(100)),
			WithNumWorkers(1),
		)
		cfg := renameMainTo(chains, "ban-30m")
		if err := re.Start(cfg); err != nil {
			t.Fatalf("Start: %v", err)
		}
		defer re.Shutdown()

		re.SendChan() <- newRequest(addr1)
		time.Sleep(100 * time.Millisecond)

		if got := jail.banCount(); got != 1 {
			t.Errorf("expected 1 ban, got %d", got)
		}
		lb := jail.lastBan()
		d := time.Until(lb.ExpiresAt)
		if d < 29*time.Minute || d > 31*time.Minute {
			t.Errorf("expected ~30m ban, got %v", d)
		}
	})

	t.Run("BAN duration 2h", func(t *testing.T) {
		jail.bans = jail.bans[:0]
		// channel is now engine-owned
		re := New(
			WithJail(jail),
			WithFileSizeIndex(fsi),
			WithCache(cache.NewCCacheCache(100)),
			WithNumWorkers(1),
		)
		cfg := renameMainTo(chains, "ban-2h")
		if err := re.Start(cfg); err != nil {
			t.Errorf("Start: %v", err)
		}
		defer re.Shutdown()

		re.SendChan() <- newRequest(addr1)
		time.Sleep(100 * time.Millisecond)

		if got := jail.banCount(); got != 1 {
			t.Errorf("expected 1 ban, got %d", got)
		}
		lb := jail.lastBan()
		d := time.Until(lb.ExpiresAt)
		if d < 119*time.Minute || d > 121*time.Minute {
			t.Errorf("expected ~2h ban, got %v", d)
		}
	})

	t.Run("BAN duration 1h30m", func(t *testing.T) {
		jail.bans = jail.bans[:0]
		// channel is now engine-owned
		re := New(
			WithJail(jail),
			WithFileSizeIndex(fsi),
			WithCache(cache.NewCCacheCache(100)),
			WithNumWorkers(1),
		)
		cfg := renameMainTo(chains, "ban-90m")
		if err := re.Start(cfg); err != nil {
			t.Fatalf("Start: %v", err)
		}
		defer re.Shutdown()

		re.SendChan() <- newRequest(addr1)
		time.Sleep(100 * time.Millisecond)

		if got := jail.banCount(); got != 1 {
			t.Errorf("expected 1 ban, got %d", got)
		}
		lb := jail.lastBan()
		d := time.Until(lb.ExpiresAt)
		if d < 89*time.Minute || d > 91*time.Minute {
			t.Errorf("expected ~90m ban, got %v", d)
		}
	})

	t.Run("LOG at various levels", func(t *testing.T) {
		var buf bytes.Buffer
		h := slog.NewJSONHandler(&buf, &slog.HandlerOptions{Level: slog.LevelDebug})
		logger := slog.New(h)

		levels := []struct {
			chain string
			text  string
		}{
			{"log-debug", "DEBUG_TEST"},
			{"log-info", "INFO_TEST"},
			{"log-warn", "WARN_TEST"},
			{"log-error", "ERROR_TEST"},
		}

		for _, lv := range levels {
			t.Run(lv.text, func(t *testing.T) {
				buf.Reset()
				// channel is now engine-owned
				re := New(
					WithJail(jail),
					WithFileSizeIndex(fsi),
					WithCache(cache.NewCCacheCache(100)),
					WithLogger(logger),
					WithNumWorkers(1),
				)
				cfg := renameMainTo(chains, lv.chain)
				if err := re.Start(cfg); err != nil {
					t.Fatalf("Start: %v", err)
				}
				defer re.Shutdown()

				re.SendChan() <- newRequest(addr1)
				time.Sleep(100 * time.Millisecond)

				if !bytes.Contains(buf.Bytes(), []byte(lv.text)) {
					t.Errorf("log output missing %q: %s", lv.text, buf.String())
				}
			})
		}
	})

	t.Run("BAN is terminal; subsequent LOG not fired", func(t *testing.T) {
		var buf bytes.Buffer
		h := slog.NewJSONHandler(&buf, &slog.HandlerOptions{Level: slog.LevelDebug})
		logger := slog.New(h)

		jail.bans = jail.bans[:0]
		// channel is now engine-owned
		re := New(
			WithJail(jail),
			WithFileSizeIndex(fsi),
			WithCache(cache.NewCCacheCache(100)),
			WithLogger(logger),
			WithNumWorkers(1),
		)
		cfg := renameMainTo(chains, "ban-then-log")
		if err := re.Start(cfg); err != nil {
			t.Fatalf("Start: %v", err)
		}
		defer re.Shutdown()

		re.SendChan() <- newRequest(addr1)
		time.Sleep(100 * time.Millisecond)

		if got := jail.banCount(); got != 1 {
			t.Errorf("expected 1 ban, got %d", got)
		}
		if bytes.Contains(buf.Bytes(), []byte("BAN_DID_NOT_STOP")) {
			t.Error("LOG after BAN should not have fired")
		}
	})

	t.Run("LOG then BAN — both fire", func(t *testing.T) {
		var buf bytes.Buffer
		h := slog.NewJSONHandler(&buf, &slog.HandlerOptions{Level: slog.LevelDebug})
		logger := slog.New(h)

		jail.bans = jail.bans[:0]
		// channel is now engine-owned
		re := New(
			WithJail(jail),
			WithFileSizeIndex(fsi),
			WithCache(cache.NewCCacheCache(100)),
			WithLogger(logger),
			WithNumWorkers(1),
		)
		cfg := renameMainTo(chains, "log-then-ban")
		if err := re.Start(cfg); err != nil {
			t.Fatalf("Start: %v", err)
		}
		defer re.Shutdown()

		re.SendChan() <- newRequest(addr1)
		time.Sleep(100 * time.Millisecond)

		if !bytes.Contains(buf.Bytes(), []byte("LOG_PRECEDES_BAN")) {
			t.Errorf("LOG didn't fire: %s", buf.String())
		}
		if got := jail.banCount(); got != 1 {
			t.Errorf("expected 1 ban, got %d", got)
		}
	})
}

